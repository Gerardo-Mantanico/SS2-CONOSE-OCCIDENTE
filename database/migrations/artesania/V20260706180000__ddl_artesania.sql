-- 11. participante_evento
CREATE TABLE IF NOT EXISTS artesania.participante_evento (
    evento_id             INT NOT NULL REFERENCES artesania.evento_exposicion_arte(id_evento) ON DELETE CASCADE,
    artista_id            INT REFERENCES artesania.artista_artesano(id_artista),
    taller_id             INT REFERENCES artesania.taller_colectivo(id_taller),
    premio_reconocimiento VARCHAR(250),
    carga_id              INT REFERENCES meta.carga(id),
    CONSTRAINT ck_artesania_participante CHECK (artista_id IS NOT NULL OR taller_id IS NOT NULL)
);

COMMENT ON TABLE artesania.participante_evento IS 'Registro de artistas y talleres colectivos participantes en eventos y sus reconocimientos.';
COMMENT ON COLUMN artesania.participante_evento.evento_id IS 'Identificador del evento.';
COMMENT ON COLUMN artesania.participante_evento.artista_id IS 'Artista individual participante (opcional).';
COMMENT ON COLUMN artesania.participante_evento.taller_id IS 'Taller colectivo participante (opcional).';
COMMENT ON COLUMN artesania.participante_evento.premio_reconocimiento IS 'Premio, mención o reconocimiento obtenido.';
COMMENT ON COLUMN artesania.participante_evento.carga_id IS 'Referencia al registro de carga de metadatos.';

